REQUIRED = {"model.mlir", "weights.safetensors", "weights.safetensors.manifest.json",
            "inputs.npz", "golden.npy", "extra.npz", "input_order.json", "source.ttir",
            "spec.json", "provenance.json", "compatibility.json", "meta.json"}

DIFFERENCES = [
    {"area": "receipt", "difference": "t2m.capture-receipt.v1, not m2m.capture-receipt.v1; no fabricated Torch identity"},
    {"area": "provenance", "difference": "provenance.json (TTIR IDs/intent/proofs), not the FX frontend-trace.json schema"},
    {"area": "parameters", "difference": "MVP has runtime inputs and one result; genuine empty weights container; parameter binding deferred"},
    {"area": "entry", "difference": "forward uses the functional tensor ABI; TTIR output pointer becomes its result"},
    {"area": "payload", "difference": "unmapped scf.forall retains source tiles; Merlin staged materialization is not claimed"},
    {"area": "verification", "difference": "xDSL round-trip and reference interpreter; strict native verifier is opt-in; native LLVM/device execution not certified"},
    {"area": "xDSL", "difference": "pinned 0.68.0 versus surveyed model2MLIR environment 0.65.0; missing standard-op bindings supplied locally"},
    {"area": "views/effects", "difference": "pointer storage layouts become logical tensors; readwrite output has incoming tensor/result; m2m registry mutation binding remains deferred"},
]


def _json(path, value):
    path.write_text(json.dumps(value, indent=2, sort_keys=True, allow_nan=False) + "\n")


def _record(path):
    value = path.read_bytes()
    return {"sha256": hashlib.sha256(value).hexdigest(), "bytes": len(value)}


def write_bundle(result, out, inputs, reference):
    """Write after checking actual emitted IR against a separately supplied golden.

    A nonempty/existing destination is never overwritten. The receipt is written
    last; its absence means this is not a complete bundle.
    """
    out = Path(out)
    if hashlib.sha256(result.mlir_text.encode()).hexdigest() != result.trace["mlir"]["sha256"]:
        raise ValueError("IR changed since conversion; provenance must be regenerated by a recorded transform")
    actual, = execute(result.mlir_text, inputs)
    reference = np.asarray(reference)
    if reference.dtype != np.float32 or reference.shape != actual.shape:
        raise ValueError("reference must match the single f32 result's exact shape")
    np.testing.assert_array_equal(actual, reference)
    module = result.module.clone()
    module.attributes["prov.weights_file"] = StringAttr("weights.safetensors")
    mlir = text(module)
    trace = deepcopy(result.trace)
    trace["mlir"] = {"sha256": hashlib.sha256(mlir.encode()).hexdigest(), "bytes": len(mlir.encode())}
    trace["execution"] = {"kind": "standard-op-reference-interpreter", "matches_supplied_golden": True}
    input_buffers = [b for b in result.spec.buffers if b.effect != "write"]
    manifest = {str(i): {"kind": "input", "name": b.name} for i, b in enumerate(input_buffers)}
    out.mkdir(parents=True, exist_ok=False)
    (out / "model.mlir").write_text(mlir)
    (out / "source.ttir").write_text(result.source_ttir)
    # Safetensors format: little-endian u64 header length + padded JSON header.
    # An empty container is valid; no source parameters are invented for a kernel.
    (out / "weights.safetensors").write_bytes(struct.pack("<Q", 8) + b"{}      ")
    _json(out / "weights.safetensors.manifest.json", manifest)
    np.savez(out / "inputs.npz", **{f"in{i}": np.asarray(x) for i, x in enumerate(inputs)})
    np.savez(out / "extra.npz")
    np.save(out / "golden.npy", reference, allow_pickle=False)
    _json(out / "input_order.json", {b.name: i for i, b in enumerate(input_buffers)})
    _json(out / "spec.json", result.spec.as_dict())
    _json(out / "provenance.json", trace)
    _json(out / "compatibility.json", {"schema": "t2m.compatibility.v1",
          "baseline": "model2MLIR 035bb5a, m2m.capture.bundle.write_bundle",
          "same_core_filenames_and_array_conventions": True, "differences": DIFFERENCES,
          "merlin_staged_execution": "not-certified"})
    _json(out / "meta.json", {"frontend": result.frontend, "output_type": result.output_type,
          "path_taken": result.path_taken, "kernel": result.spec.entry,
          "reference_execution": "passed", "merlin_staged_execution": "not-certified"})
    receipt = {"schema": "t2m.capture-receipt.v1", "tool": "triton2mlir", "toolchain": trace["toolchain"],
               "artifacts": {name: _record(out / name) for name in sorted(REQUIRED)},
               "source_closure_verified": False,
               "materialized_abi": {"complete": True, "inputs": len(inputs), "outputs": 1}}
    _json(out / "capture_receipt.json", receipt)
    verify_bundle(out)
    return out


def verify_bundle(out):
    out = Path(out)
    receipt = json.loads((out / "capture_receipt.json").read_text())
    if receipt.get("schema") != "t2m.capture-receipt.v1" or set(receipt.get("artifacts", {})) != REQUIRED:
        raise ValueError("not a complete t2m capture receipt")
    for name, record in receipt["artifacts"].items():
        path = out / name
        if path.is_symlink() or not path.is_file() or _record(path) != record:
            raise ValueError(f"bundle integrity mismatch: {name}")
    provenance = json.loads((out / "provenance.json").read_text())
    if provenance["mlir"] != _record(out / "model.mlir"):
        raise ValueError("provenance does not bind exact model.mlir bytes")
    from .spec import KernelSpec
    spec = KernelSpec.from_dict(json.loads((out / "spec.json").read_text()))
    if provenance["spec_sha256"] != spec.digest:
        raise ValueError("provenance does not bind the resolved spec")
    if provenance["source"]["sha256"] != _record(out / "source.ttir")["sha256"]:
        raise ValueError("provenance does not bind the source TTIR")
    order = json.loads((out / "input_order.json").read_text())
    with np.load(out / "inputs.npz", allow_pickle=False) as data:
        if sorted(order.values()) != list(range(len(order))) or set(data.files) != {f"in{i}" for i in range(len(order))}:
            raise ValueError("input ordering is incomplete")
    return receipt

